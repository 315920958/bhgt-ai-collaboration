#!/usr/bin/env bash
#
# 通过 SSH 本地端口转发，从本机连接到线上服务器的 MongoDB（用户口语称 "mango"）。
#
# 原理（ssh -L）：
#   在「本机」监听 47017，把流量经 SSH 隧道转发到
#   「远端服务器」自身的 127.0.0.1:27017（即线上 MongoDB 的监听地址）。
#   建立后，本机用 `mongosh mongodb://localhost:47017` 即可像访问本地库一样访问线上库。
#
# 用法：
#   1) 运行本脚本（保持终端打开，隧道即生效）
#   2) 另开终端：mongosh mongodb://localhost:47017
#   3) 用完按 Ctrl+C 关闭隧道
#
# 说明：这是「本地转发」(ssh -L)，作用是把远端服务映射到本机端口，
#       便于在本机用 GUI/CLI 工具安全地访问线上数据库（无需把 27017 暴露到公网）。

ssh -NL 47017:127.0.0.1:27017 ubuntu@49.232.103.103
